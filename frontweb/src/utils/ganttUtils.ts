import { Tarefa } from 'types/tarefa';

// Product decisions for the timeline. Each one is a single switch here on purpose.
// Confirmed with the team 2026-11-06: archived tarefas must be visible once a
// projeto ends (see arquivadasVisiveisPorDefeito). Progress weighting and the
// risk threshold kept their proposed defaults.
export const GANTT_CONFIG = {
  // Progress weighted by each tarefa's working days (true) or a plain count (false).
  progressoPonderado: true,
  // Percentage points by which elapsed time may run ahead of progress before a
  // phase is flagged "Em risco".
  limiarRiscoPontos: 20,
  // Occurrences generated by the recurrence scheduler get no row of their own (the
  // template stays, with a summary of its occurrences); they still count in the
  // phase's progress and deviation.
  esconderOcorrenciasRecorrentes: true,
};

// Initial state of the "Mostrar arquivadas" toggle: on for a projeto that has
// ended (concluded or archived), so its full history is visible; off otherwise.
export const arquivadasVisiveisPorDefeito = (projeto: {
  status?: string | null;
  arquivadaEm?: string | null;
}): boolean => projeto.status === 'CONCLUIDO' || !!projeto.arquivadaEm;

export type EstadoFase =
  | 'SEM_TAREFAS'
  | 'NAO_INICIADA'
  | 'EM_CURSO'
  | 'EM_RISCO'
  | 'ATRASADA'
  | 'CONCLUIDA';

export const ESTADO_FASE_LABELS: Record<EstadoFase, string> = {
  SEM_TAREFAS: 'Sem tarefas',
  NAO_INICIADA: 'Não iniciada',
  EM_CURSO: 'Em curso',
  EM_RISCO: 'Em risco',
  ATRASADA: 'Atrasada',
  CONCLUIDA: 'Concluída',
};

export interface Periodo {
  inicio: Date;
  fim: Date;
}

const DIA_MS = 24 * 60 * 60 * 1000;

// Backend dates arrive as 'yyyy-MM-dd' (LocalDate) or a full ISO timestamp
// (java.util.Date). Only the calendar day matters, read as local midnight so a
// UTC timestamp never shifts the bar by a day.
export const parseDia = (valor?: string | null): Date | null => {
  if (!valor) return null;
  const [ano, mes, dia] = valor.split('T')[0].split('-').map(Number);
  if (!ano || !mes || !dia) return null;
  return new Date(ano, mes - 1, dia);
};

export const inicioDoDia = (data: Date): Date =>
  new Date(data.getFullYear(), data.getMonth(), data.getDate());

// Whole days from a to b (b - a), robust to DST changes.
export const diasEntre = (a: Date, b: Date): number =>
  Math.round((inicioDoDia(b).getTime() - inicioDoDia(a).getTime()) / DIA_MS);

// Start and end of a tarefa. A tarefa with only one date is drawn as a single day.
export const periodoTarefa = (tarefa: Tarefa): Periodo | null => {
  const inicio = parseDia(tarefa.prazoEstimado);
  const fim = parseDia(tarefa.prazoReal);
  if (!inicio && !fim) return null;
  const a = (inicio ?? fim) as Date;
  const b = (fim ?? inicio) as Date;
  return a <= b ? { inicio: a, fim: b } : { inicio: b, fim: a };
};

// Planned period of a phase; a phase with only one planned date is a single day.
export const periodoPlaneado = (fase: ProjetoFase): Periodo | null => {
  const inicio = parseDia(fase.dataInicio);
  const fim = parseDia(fase.dataFim);
  if (!inicio && !fim) return null;
  return { inicio: (inicio ?? fim) as Date, fim: (fim ?? inicio) as Date };
};

// Actual span covered by a set of tarefas (earliest start to latest end).
export const periodoReal = (tarefas: Tarefa[]): Periodo | null =>
  unirPeriodos(tarefas.map(periodoTarefa));

export const unirPeriodos = (periodos: (Periodo | null)[]): Periodo | null => {
  const validos = periodos.filter((p): p is Periodo => p !== null);
  if (validos.length === 0) return null;
  return {
    inicio: new Date(Math.min(...validos.map((p) => p.inicio.getTime()))),
    fim: new Date(Math.max(...validos.map((p) => p.fim.getTime()))),
  };
};

// Percentage (0-100, rounded) of the phase's work that is DONE.
export const progressoFase = (
  tarefas: Tarefa[],
  ponderado: boolean = GANTT_CONFIG.progressoPonderado,
): number => {
  if (tarefas.length === 0) return 0;
  const peso = (t: Tarefa) => (ponderado ? Math.max(t.workingDays ?? 1, 1) : 1);
  const total = tarefas.reduce((soma, t) => soma + peso(t), 0);
  const feito = tarefas
    .filter((t) => t.status === 'DONE')
    .reduce((soma, t) => soma + peso(t), 0);
  return Math.round((feito / total) * 100);
};

// The tarefa's plan: the frozen estimate when the backend recorded one, else its
// current duration (tarefas created before the estimate existed).
export const diasEstimadosTarefa = (t: Tarefa): number | null =>
  t.diasEstimados ?? t.workingDays ?? null;

// Working days actually spent on the work: the real duration minus the time in
// review (waiting for a reviewer is not the collaborator's time).
export const diasTrabalhoTarefa = (t: Tarefa): number | null =>
  t.diasTrabalho ?? t.diasReais ?? null;

// Work days minus estimated days of a DONE tarefa; null when it can't be measured
// (not DONE, or no completion date / estimate recorded).
export const desvioTarefa = (t: Tarefa): number | null => {
  const estimados = diasEstimadosTarefa(t);
  const trabalho = diasTrabalhoTarefa(t);
  if (t.status !== 'DONE' || trabalho == null || estimados == null) return null;
  return trabalho - estimados;
};

export interface ResumoRevisao {
  // Working days spent in review, every round of every tarefa added up.
  dias: number;
  devolucoes: number;
}

// Null when no tarefa of the group has been through review yet.
export const resumoRevisao = (tarefas: Tarefa[]): ResumoRevisao | null => {
  const dias = tarefas.reduce((soma, t) => soma + (t.diasEmRevisao ?? 0), 0);
  const devolucoes = tarefas.reduce((soma, t) => soma + (t.devolucoes ?? 0), 0);
  return dias > 0 || devolucoes > 0 ? { dias, devolucoes } : null;
};

export const textoDevolucoes = (n: number): string =>
  `${n} ${n === 1 ? 'devolução' : 'devoluções'}`;

export interface ResumoDesvio {
  // Tarefas with a measurable deviation.
  medidas: number;
  total: number;
  // Rounded to one decimal.
  medio: number;
  // Largest overrun (the most negative value when every tarefa finished early).
  pior: number;
}

export const resumoDesvio = (tarefas: Tarefa[]): ResumoDesvio | null => {
  const desvios = tarefas.map(desvioTarefa).filter((d): d is number => d != null);
  if (desvios.length === 0) return null;
  const total = desvios.reduce((soma, d) => soma + d, 0);
  return {
    medidas: desvios.length,
    total,
    medio: Math.round((total / desvios.length) * 10) / 10,
    pior: Math.max(...desvios),
  };
};

// "+2 dias", "-1 dia", "0 dias" (decimals with a comma, as in pt-PT).
export const textoDesvio = (dias: number): string => {
  const sinal = dias > 0 ? '+' : '';
  const numero = String(dias).replace('.', ',');
  return `${sinal}${numero} ${Math.abs(dias) === 1 ? 'dia' : 'dias'}`;
};

// Compact form for labels next to the bars: "+2 d".
export const textoDesvioCurto = (dias: number): string =>
  `${dias > 0 ? '+' : ''}${String(dias).replace('.', ',')} d`;

export interface DiasFase {
  // Working days estimated across the tarefas that have both dates.
  estimados: number;
  // Of those, the working days of tarefas already DONE.
  concluidos: number;
  // Tarefas left out of the sums because they have no working-days value.
  semEstimativa: number;
}

// Estimated working days of a phase, shown on hover next to the % progress.
export const diasFase = (tarefas: Tarefa[]): DiasFase =>
  tarefas.reduce<DiasFase>(
    (acc, t) => {
      const dias = diasEstimadosTarefa(t);
      if (dias == null) return { ...acc, semEstimativa: acc.semEstimativa + 1 };
      return {
        ...acc,
        estimados: acc.estimados + dias,
        concluidos: acc.concluidos + (t.status === 'DONE' ? dias : 0),
      };
    },
    { estimados: 0, concluidos: 0, semEstimativa: 0 },
  );

export const textoDias = (dias: number): string => `${dias} ${dias === 1 ? 'dia útil' : 'dias úteis'}`;

// Share (0-100) of the period already elapsed on `hoje`, counting both ends.
export const tempoDecorrido = (periodo: Periodo, hoje: Date): number => {
  const duracao = diasEntre(periodo.inicio, periodo.fim) + 1;
  const decorridos = diasEntre(periodo.inicio, hoje) + 1;
  return Math.min(Math.max((decorridos / duracao) * 100, 0), 100);
};

// `periodo` is the planned period when the phase has one, otherwise the span
// of its tarefas, so phases without planned dates still get a state.
export const estadoFase = (
  periodo: Periodo | null,
  progresso: number,
  numTarefas: number,
  hoje: Date,
  limiar: number = GANTT_CONFIG.limiarRiscoPontos,
): EstadoFase => {
  if (numTarefas === 0) return 'SEM_TAREFAS';
  if (progresso >= 100) return 'CONCLUIDA';
  if (!periodo) return progresso > 0 ? 'EM_CURSO' : 'NAO_INICIADA';

  const dia = inicioDoDia(hoje);
  if (dia < periodo.inicio) return 'NAO_INICIADA';
  if (dia > periodo.fim) return 'ATRASADA';
  if (tempoDecorrido(periodo, dia) - progresso > limiar) return 'EM_RISCO';
  return 'EM_CURSO';
};

// Tarefas that get a row of their own: drops the occurrences spawned by the
// recurrence scheduler (they point back to their template through
// tarefaOrigemId); the template itself stays.
export const filtrarTarefasGantt = (
  tarefas: Tarefa[],
  esconderRecorrentes: boolean = GANTT_CONFIG.esconderOcorrenciasRecorrentes,
): Tarefa[] =>
  esconderRecorrentes ? tarefas.filter((t) => !t.tarefaOrigemId) : tarefas;

export interface EixoTemporal {
  inicio: Date;
  fim: Date;
  totalDias: number;
  meses: { inicio: Date; dias: number; rotulo: string }[];
}

const MESES_PT = ['Jan', 'Fev', 'Mar', 'Abr', 'Mai', 'Jun', 'Jul', 'Ago', 'Set', 'Out', 'Nov', 'Dez'];

// Axis from the first day of the earliest month to the last day of the latest
// month covering every period given (plus today, so the "hoje" line is visible).
export const construirEixo = (periodos: (Periodo | null)[], hoje: Date): EixoTemporal => {
  const uniao = unirPeriodos([...periodos, { inicio: inicioDoDia(hoje), fim: inicioDoDia(hoje) }]) as Periodo;
  const inicio = new Date(uniao.inicio.getFullYear(), uniao.inicio.getMonth(), 1);
  const fim = new Date(uniao.fim.getFullYear(), uniao.fim.getMonth() + 1, 0);

  const meses: EixoTemporal['meses'] = [];
  for (let m = new Date(inicio); m <= fim; m = new Date(m.getFullYear(), m.getMonth() + 1, 1)) {
    const ultimo = new Date(m.getFullYear(), m.getMonth() + 1, 0);
    meses.push({
      inicio: m,
      dias: ultimo.getDate(),
      rotulo: `${MESES_PT[m.getMonth()]} ${m.getFullYear()}`,
    });
  }
  return { inicio, fim, totalDias: diasEntre(inicio, fim) + 1, meses };
};

// Horizontal position of a period on the axis, as CSS percentages.
export const posicaoNoEixo = (
  periodo: Periodo,
  eixo: EixoTemporal,
): { left: string; width: string } => {
  const offset = diasEntre(eixo.inicio, periodo.inicio);
  const duracao = diasEntre(periodo.inicio, periodo.fim) + 1;
  return {
    left: `${(offset / eixo.totalDias) * 100}%`,
    width: `${(duracao / eixo.totalDias) * 100}%`,
  };
};

// Position of a single day's start (for vertical markers such as "hoje").
export const posicaoDia = (dia: Date, eixo: EixoTemporal): string =>
  `${(diasEntre(eixo.inicio, dia) / eixo.totalDias) * 100}%`;

export const formatarDia = (data: Date): string =>
  data.toLocaleDateString('pt-PT', { day: '2-digit', month: '2-digit', year: 'numeric' });
